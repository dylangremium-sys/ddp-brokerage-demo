// ─── Public page metadata register ──────────────────────────────────────────
//
// WHY THIS EXISTS
//   index.html carries ONE title and ONE description, and `vercel.json` rewrites
//   every non-API path to that one document. So before this module, every URL on
//   the site — `/`, `/farmer`, and now the corporate pages — presented a crawler
//   with identical metadata. Adding real corporate pages without this would have
//   produced four URLs that search engines are entitled to treat as duplicates
//   of the landing page.
//
//   index.html says so itself: it carries no <link rel="canonical"> because a
//   static one would claim to describe `/farmer` too, and defers the per-page
//   case to "the per-page metadata work". This is that work.
//
// SHAPE OF THE FIX
//   A static map from Page to metadata, plus a thin applier that writes it into
//   the document head. The map is pure data and the decision logic is pure, so
//   the register is testable in the repo's default `environment: 'node'` suite;
//   only `applyPublicPageMetadata` touches the DOM, and it takes the Document as
//   an argument rather than reaching for a global.
//
// THE SAFETY PROPERTY THAT MATTERS MOST
//   Metadata is only ever READ FROM THIS FILE. No caller may pass a title or a
//   description in. That is what makes it structurally impossible for a farm
//   name, a batch id, a buyer's organisation or any other operational record to
//   reach the document head — where it would be read by a crawler, sent in a
//   referrer, and shown in a browser tab and history. A `page` is an enum
//   member; there is no channel through which a record could arrive.

import type { Page } from '../types'

/**
 * The approved production origin.
 *
 * The apex 308-redirects to www, so www is the canonical host — a canonical URL
 * on the apex would point a crawler at a redirect instead of at the page. This
 * is the same constant the crawl-policy files are asserted against, and the
 * sitemap is generated by hand against it.
 */
export const CANONICAL_ORIGIN = 'https://www.ddpbrokerage.com'

/**
 * The metadata model from the search-exposure master plan, section 9 (Phase 4).
 * The plan's field list is the contract; this is that interface verbatim.
 */
export interface PublicPageMetadata {
  title: string
  description: string
  canonicalPath: string
  robots: 'index,follow' | 'noindex,nofollow'
  /**
   * The document language, written into `<html lang>` on the prerendered page.
   *
   * Absent means English, which is what index.html declares and what every page
   * but /de is written in. A wrong `lang` is not cosmetic: it is what a screen
   * reader uses to choose a voice, and what a search engine uses to decide
   * which country's results a page belongs in.
   */
  lang?: 'en' | 'de' | 'cs' | 'th'
  /**
   * The date this page's content was last reviewed, as YYYY-MM-DD.
   *
   * AUTHORED, NEVER DERIVED. It was briefly derived from git — the date of the
   * last commit touching a page's sources — and that had two faults. It said
   * "this file changed", which is not the same claim as "a person checked this
   * page is still true"; and it could not be trusted on a CI host, because
   * `git log -1` in a shallow clone returns the boundary commit rather than
   * failing, reporting files untouched for months as changed that week.
   *
   * This is the ONE place the date lives. The sitemap's <lastmod> reads it, and
   * so does the "last reviewed" line the page itself displays — so a visitor
   * and a search engine cannot be told different things, which is what happened
   * while the shells hardcoded their own copy of it.
   */
  lastReviewed: string
}

