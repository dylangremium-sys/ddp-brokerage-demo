/**
 * What any page not named in the register gets.
 *
 * Fail-closed: an unknown page is `noindex,nofollow` with a generic title and
 * no description. Every authenticated surface in the application falls here, so
 * adding an admin, farmer or buyer screen can never make one indexable by
 * omission — the only way to publish a page is to add it to the register above
 * and to the sitemap, which is a visible policy edit in a reviewed diff.
 */
